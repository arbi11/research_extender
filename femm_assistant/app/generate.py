def source_files(spec: CCoreSpec) -> dict[str, str]:
    return {"model.lua": lua_script(spec), "run.py": RUNNER,
            "spec.json": json.dumps(spec.model_dump(), indent=2) + "\n",
            "geometry.svg": preview_svg(spec), "README.txt": EXPORT_README}


def source_zip(spec: CCoreSpec) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, content in source_files(spec).items():
            archive.writestr(name, content)
    return buf.getvalue()
